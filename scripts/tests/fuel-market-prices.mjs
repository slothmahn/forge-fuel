import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../../assets/fuel-market-prices.js', import.meta.url), 'utf8');
const {loadFuelMarketPrices} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
let saved = '{}';
const storage = {getItem:()=>saved, setItem:(_,value)=>saved=value};
const pairs = {fuel:'0x1', more:'0x2'};
let release;
const slow = new Promise(resolve => release=resolve);
const updates=[];
const response = (address)=>({ok:true,json:async()=>({pairs:[{chainId:'robinhood',pairAddress:address,priceUsd:'2',priceNative:'0.001'}]})});
const pending = loadFuelMarketPrices({chain:'robinhood',pairs,storage,now:()=>1000000,onUpdate:(q,s)=>updates.push({q,s}),request:async url=>url.endsWith('0x1')?response('0x1'):slow});
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(updates.at(-1).q.fuel.price,2, 'Fast price displays before slow request completes');
assert.equal(updates.at(-1).q.more,undefined);
release(response('0x2')); await pending;
const cached=[];
await loadFuelMarketPrices({chain:'robinhood',pairs,storage,now:()=>1001000,onUpdate:(q,s)=>cached.push({q,s}),request:async()=>{throw Error('offline')}});
assert.equal(cached[0].q.more.price,2,'Cache renders immediately');
assert.equal(cached.at(-1).q.fuel.price,2,'Failed refresh preserves recent quotes');
assert.equal(cached.at(-1).s.failed,2);
const expired=[];
await loadFuelMarketPrices({chain:'robinhood',pairs,storage,now:()=>2000000,onUpdate:q=>expired.push(q),request:async()=>{throw Error('offline')}});
assert.deepEqual(expired[0],{},'Expired references are not reused');
console.log('PASS: progressive loading, immediate cache, failure retention, cache expiry');
